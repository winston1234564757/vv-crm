/**
 * Пояс рантайму = пояс магазину.
 *
 * Серверні компоненти рендеряться там, де стоїть рантайм, а на Vercel це
 * завжди UTC. Через це чек, пробитий о 12:03, показувався як 09:03, а
 * `resolveRange("today")` брав UTC-північ замість київської — з 00:00 до 03:00
 * дашборд вважав, що триває попередній день.
 *
 * Змінною оточення це не лікується: `TZ` у Vercel зарезервоване ім'я, додати
 * його в налаштування проєкту не дає API. Тому пояс виставляється тут —
 * `register` викликається один раз на інстанс сервера і мусить завершитись до
 * того, як сервер почне приймати запити, тож жоден `new Date()` у застосунку
 * не встигає побачити UTC.
 *
 * Node з v16 скидає закешований пояс при зміні `process.env.TZ`, тому
 * присвоєння тут справді впливає на `Date` — це не мертвий код.
 *
 * Edge виключено навмисно: там V8-ізолят із прибитим UTC, `process.env.TZ`
 * нічого не змінює. Дат у `proxy.ts` немає, тож втрачати нічого.
 *
 * Явний `timeZone` у форматувальниках (`lib/utils/day.ts`) лишається: він не
 * дублює цей файл, а страхує від нього. Якщо пояс колись знову з'їде, підписи
 * часу все одно будуть київські.
 */
export function register() {
  if (process.env.NEXT_RUNTIME === "nodejs") {
    process.env.TZ = "Europe/Kyiv";
  }
}
