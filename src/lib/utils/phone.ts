/**
 * Порівняння українських номерів, записаних по-різному.
 *
 * У базі номери лежать так, як їх набрали: `0982180430`, `+380982180430`,
 * `38 (098) 218-04-30`. Це той самий абонент, але рядки різні, тож пошук по
 * точному збігу його не знаходить — і користувач починає заводити клієнта
 * заново, впираючись в унікальний індекс на телефон.
 *
 * Спільний у всіх записах — хвіст із дев'яти цифр (код оператора + номер).
 * Порівнюємо саме його.
 */
export function phoneKey(phone: string | null | undefined): string {
  const digits = (phone ?? "").replace(/\D/g, "");
  return digits.length >= 9 ? digits.slice(-9) : "";
}

/** Чи вказують два записи на один номер. Порожні ніколи не збігаються. */
export function samePhone(a: string | null | undefined, b: string | null | undefined): boolean {
  const ka = phoneKey(a);
  return ka !== "" && ka === phoneKey(b);
}
