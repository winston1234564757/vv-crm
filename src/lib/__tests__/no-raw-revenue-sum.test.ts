import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";

/**
 * Виторг рахує рівно один модуль — `lib/profit.ts`. Найімовірніший спосіб це
 * зламати — підсумувати `total_amount` чи `price` reduce-ом у новому місці:
 * число вийде правдоподібне, а від дашборду розійдеться мовчки. Саме так
 * жили «Звіти» (32 610 ₴ проти 27 460 ₴) і аналітика до 30.07.
 *
 * Тест ловить форму запису, а не наслідок, і охороняє лише перелічені файли.
 *
 * `data-analytics.ts` у списку НЕМАЄ: він рахує партнерські суми напряму, але
 * над рядками, уже відфільтрованими епохою, і жодна з них не подається як
 * виторг магазину. Це рішення на сьогодні, а не гарантія — якщо там колись
 * заведеться справжній виторг, цей тест його не побачить, бо файл поза
 * списком. Тоді треба додати файл сюди, а не сподіватись на автоматику.
 *
 * `data-day.ts` немає з іншої причини: файл з'явиться у слайсі 2, і додати
 * його має той слайс. Рядок із `try/catch` на неіснуючий файл був би тестом,
 * який нічого не стверджує, — гірше за відсутній.
 *
 * Межі захисту, перевірені емпірично: регекс ловить буквальний
 * `reduce(... .total_amount)`, але проходять повз нього деструктуризація
 * (`(sum, {total_amount}) => ...`), дужкова нотація (`s["total_amount"]`),
 * звичайний `for` із `+=`, рознесені `.map().reduce()` і хелпер, винесений у
 * невартовий файл. Це grep по найімовірнішому регресу, а не аналіз AST —
 * і саме такий регрес він щойно зловив на живому коді (`getSalesStats`).
 */
const GUARDED = ["src/lib/data-dashboard.ts", "src/lib/data-sales.ts", "src/lib/data-finance.ts"];

const RAW_SUM = /reduce\([\s\S]{0,120}\.(total_amount|total_price)\b/g;

describe("виторг рахується лише через profit.ts", () => {
  for (const file of GUARDED) {
    it(`${file} не підсумовує total_amount/total_price напряму`, () => {
      expect(readFileSync(file, "utf8").match(RAW_SUM)).toBeNull();
    });
  }
});
