import { describe, it, expect } from "vitest";
import { weightedCost } from "../inventory-cost";

describe("weightedCost", () => {
  it("порожня картка бере ціну партії як є", () => {
    expect(weightedCost(0, 0, 10, 150)).toBe(150);
  });

  it("стара собівартість не тягне вниз, коли залишку немає", () => {
    // Класичний випадок: кабель закінчився, cost_price лишився з торішньої
    // партії. Зважувати нема чого — на складі нуль штук по 100.
    expect(weightedCost(0, 100, 10, 150)).toBe(150);
  });

  it("зважує старий залишок із новою партією", () => {
    // 2 × 100 + 8 × 150 = 1400 на 10 шт
    expect(weightedCost(2, 100, 8, 150)).toBe(140);
  });

  it("однакова ціна лишає собівартість на місці", () => {
    expect(weightedCost(5, 120, 5, 120)).toBe(120);
  });

  it("округлює до гривні", () => {
    // 1 × 100 + 2 × 151 = 402 на 3 шт = 134.0
    expect(weightedCost(1, 100, 2, 151)).toBe(134);
    // 1 × 100 + 1 × 151 = 251 на 2 шт = 125.5 → 126
    expect(weightedCost(1, 100, 1, 151)).toBe(126);
  });

  it("безкоштовна партія розмиває собівартість, а не обнуляє її", () => {
    // Зразок від постачальника: 2 шт по 100 плюс 2 шт по 0 = 50 за штуку.
    expect(weightedCost(2, 100, 2, 0)).toBe(50);
  });

  it("нульова кількість приходу лишає стару собівартість", () => {
    expect(weightedCost(4, 130, 0, 999)).toBe(130);
  });

  it("відʼємний залишок рахується як нуль, а не як відʼємний внесок", () => {
    // У базі такого стану немає — списання впаде раніше. Але мовчазний
    // відʼємний внесок дав би собівартість, більшу за ціну партії.
    expect(weightedCost(-5, 100, 10, 150)).toBe(150);
  });

  it("порожній склад і порожній прихід не діляться на нуль", () => {
    expect(weightedCost(0, 0, 0, 0)).toBe(0);
    expect(weightedCost(0, 0, 0, 200)).toBe(200);
  });
});
