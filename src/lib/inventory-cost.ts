/**
 * Собівартість картки товару після приходу нової партії.
 *
 * У картки аксесуара одне поле `cost_price` на весь залишок, а партії
 * приходять за різними цінами. Було 2 шт по 100, прийшло 8 шт по 150 — на
 * складі 10 шт, і жодне з двох чисел уже не описує їх усі.
 *
 * Тому середньозважена: 140 ₴. Жодна конкретна закупівля стільки не коштувала,
 * і це нормально — число описує не покупку, а склад. Альтернатива «перезаписати
 * останньою ціною» оцінила б дві старі штуки по 150 і завищила «Вартість
 * бізнесу» на 100 ₴ рівно на порожньому місці.
 *
 * Минулі продажі це не переписує: `sale_items.unit_cost` — знімок на момент
 * чека, і рушій прибутку читає саме його.
 *
 * Форма підставляє це число й дозволяє його перебити. Округлення до гривні
 * тут не косметика: усі гроші в проєкті цілі, і дробова собівартість поїхала б
 * у першому ж множенні на залишок.
 */
export function weightedCost(
  stock: number,
  cost: number,
  quantity: number,
  unitCost: number,
): number {
  /* Відʼємний залишок зважувати нічим. У базі він неможливий — списання
     впаде раніше, — але функція чиста, і мовчазний відʼємний внесок був би
     гіршою відповіддю за нуль. */
  const have = Math.max(stock, 0);
  const coming = Math.max(quantity, 0);
  const units = have + coming;

  // Порожня картка й порожній прихід: середньої немає, беремо ціну партії.
  if (units === 0) return Math.max(Math.round(unitCost), 0);

  const total = have * Math.max(cost, 0) + coming * Math.max(unitCost, 0);
  return Math.round(total / units);
}
