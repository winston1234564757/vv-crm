/**
 * Ролі й правила доступу без жодних серверних залежностей.
 *
 * Живе окремо від `rbac.ts` навмисно: `rbac.ts` тягне `next/navigation` і
 * supabase-клієнт, тож клієнтські компоненти (сайдбар, мобільна навігація)
 * не можуть імпортувати з нього значення — тільки типи. Цей файл вільно
 * імпортується з обох боків межі.
 */

export type UserRole = "owner" | "manager" | "technician" | "sales";

/**
 * Ролі, яким видно гроші: прибуток, маржа, собівартість, залишки кас і
 * сейфів, частки власників, OPEX-резерв.
 *
 * Один список на всі місця перевірки — сторінки фінансів і звітів, AI-роути,
 * навігація, грошові клітинки дашборду. Розійтись вони можуть тільки разом.
 *
 * Це не робить виторг таємницею: список продажів (`/admin/sales`) лишається
 * відкритим для всіх, бо продавець ці чеки сам і пробиває. Ховається зведена
 * картина — прибуток, собівартість, залишки, частки.
 */
export const MONEY_ROLES: UserRole[] = ["owner", "manager"];

export function canSeeMoney(role: UserRole | null | undefined): boolean {
  return !!role && MONEY_ROLES.includes(role);
}
