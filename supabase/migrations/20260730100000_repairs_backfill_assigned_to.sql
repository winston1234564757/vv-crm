-- Ремонти без майстра: аналітика продажів зводила їхній виторг у «Невідомо».
--
-- `repairs.assigned_to` не заповнювалось ніколи — ані формою прийому, ані
-- жодною дією. `sales_analytics` бере продавця ремонту саме звідси
-- (`left join profiles on p.id = r.assigned_to`), тож усі 17 ремонтів магазину
-- падали в один рядок «Невідомо» поруч із власником, який їх і зробив.
--
-- Код прийому тепер пише `assigned_to = auth.uid()` (`createRepair`). Цей
-- бекфіл закриває історію: у магазині працює одна людина, інших профілів із
-- роллю owner до ремонтів не було, тож усі минулі ремонти — її.
--
-- Складські ремонти (`inventory_device_id is not null`) теж підписуємо: вони в
-- аналітику продажів не входять, але лишати половину таблиці порожньою означає
-- тримати ту саму пастку для наступного звіту.
update repairs r
set assigned_to = p.id
from profiles p
where r.assigned_to is null
  and p.full_name = 'viktor.koshel24@gmail.com';
