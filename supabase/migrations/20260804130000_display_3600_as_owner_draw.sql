-- Дисплей 13 Pro Max за 3 600 — не витрата магазину, а частка власників.
--
-- Було: витрата категорії «Обладнання», оплачена БЕЗГОТІВКОЮ з сейфа Growth
-- 01.08 о 17:48. «Обладнання» — не капітальна категорія (капітальна тут
-- «Капітал / Відкриття»), тож ці 3 600 сиділи в операційних витратах і різали
-- прибуток 01.08.
--
-- Стало: два вилучення частки по 1 800 — по одному на власника, тим самим
-- числом. Витрата зникає: інакше ті самі гроші вийшли б з бізнесу двічі — раз
-- як «Обладнання», раз як частка.
--
-- ДЖЕРЕЛО — GROWTH, А НЕ СЕЙФ ЧП, І ЦЕ НЕ ОПИСКА.
-- Просили «зняття з сейфа чистого прибутку». Взяти звідти нічим: 04.08 о 13:01
-- звідти пішло «Службове вилучення» на 4 000 і сейф став 0/0, а на саме 01.08
-- він і поготів був порожній — 20260803120000 розбирає, як його загнали в
-- −3 498 вилученням 12 000 того ж дня. Від'ємну половину блокує CHECK
-- `safes_halves_non_negative` (20260803140000).
-- Тому це записано тим механізмом, який система для цього й має, — авансом:
-- гроші, взяті власниками наперед, повз сейф ЧП. `buildLedger` впізнає їх за
-- тим, що джерело ≠ ЧП, і позначає рядок «аванс».
-- Growth тут не довільний вибір, а той самий сейф, чия картка за дисплей і
-- заплатила. Тобто рядок каже правду про те, звідки пішли гроші.
--
-- НА ЧАСТКИ ЦЕ ВПЛИВАЄ РІВНО ТАК, ЯК ПРОСИЛИ. Аванс бази нарахування не
-- збільшує (цих грошей сейф ЧП не бачив), але проти власника рахується
-- повністю: «знято» кожному +1 800, «доступно» кожному −1 800. Те саме, що дало
-- б зняття з ЧП, якби там було з чого знімати. Різниця лише в мітці «аванс» —
-- і вона тут чесна: обидва взяли наперед.
--
-- БАЛАНСИ НЕ РУХАЮТЬСЯ ЖОДНІ, І ЦЕ НАВМИСНО.
-- Гроші пішли 01.08 — тоді ж Growth і втратив свої 3 600 безготівки. Сьогодні
-- нічого не переміщується, змінюється лише назва події. Тому старий рядок
-- видаляється НАПРЯМУ, а не через `delete_transaction`: та функція зробила б
-- сторно й повернула б Growth 3 600 безготівки, яких на картці немає — у
-- системі стало б 8 850 проти 5 250 наживо. Купюр лишається 19 100, на картці
-- 5 250, обидва числа збігаються з тим, що власник полічив 03.08.
-- Звірка «леджер проти балансу» теж не ламається: один відтік на 3 600
-- замінено двома відтоками, що дають ті самі 3 600.
--
-- ЧОМУ ДВА РЯДКИ, А НЕ ОДИН НА 3 600. `buildLedger` розносить вилучення по
-- власниках рівно за `created_by`. Один рядок записав би всі 3 600 на того, хто
-- його створив, і другий власник у списку зняттів виглядав би чистим.
--
-- ПОБІЧНИЙ ЕФЕКТ, ЯКИЙ ТРЕБА ЗНАТИ: прибуток 01.08 виросте на 3 600 — витрат
-- того дня стало менше. Подвійного рахунку немає: нарахування рахується з
-- балансу сейфа ЧП, а не із заробленого; `totalNet` лишається довідковим.
--
-- Прив'язка за описом і сумою, а не за зашитим id: id згенерований, а такий
-- рядок у базі рівно один. Повторний запуск нічого не робить.

do $$
declare
  v_exp    public.expenses%rowtype;
  v_tx     public.transactions%rowtype;
  v_owners uuid[];
  v_names  text[];
  v_half   integer;
  i        integer;
begin
  select * into v_exp
    from public.expenses
   where amount = 3600
     and description = 'iPhone13 Pro Max дисплей';

  if not found then
    raise notice 'Витрати на дисплей 3 600 немає — уже перекваліфіковано або не було.';
    return;
  end if;

  if v_exp.amount % 2 <> 0 then
    raise exception 'Сума % не ділиться навпіл без копійок', v_exp.amount;
  end if;
  v_half := v_exp.amount / 2;

  -- Рівно двоє власників з рівними частками — те саме припущення, на якому
  -- стоїть `buildLedger`. Третій зламав би 50/50, і краще впасти тут.
  select array_agg(id order by created_at),
         array_agg(coalesce(full_name, 'Без імені') order by created_at)
    into v_owners, v_names
    from public.profiles where role = 'owner';

  if array_length(v_owners, 1) <> 2 then
    raise exception 'Очікували двох власників, знайшли %', coalesce(array_length(v_owners, 1), 0);
  end if;

  -- Транзакція витрати. Беремо всю, а не лише id: з неї йдуть час, джерело й
  -- спосіб оплати для нових рядків — щоб вони описували ТУ САМУ подію, а не
  -- схожу на неї.
  select * into v_tx
    from public.transactions
   where reference_type = 'expense'
     and amount = v_exp.amount
     and description = v_exp.description
     and from_type = 'safe'
     and from_id = v_exp.paid_from_safe_id
   order by created_at
   limit 1;

  if not found then
    raise exception 'Транзакцію витрати не знайдено — зупиняємось, щоб не лишити її сиротою';
  end if;

  delete from public.transactions where id = v_tx.id;
  delete from public.expenses where id = v_exp.id;

  -- +1 і +2 секунди до часу оригіналу, щоб порядок у списку не залежав від
  -- випадку (той самий прийом, що в 20260803150000).
  for i in 1..2 loop
    insert into public.transactions (
      amount, from_type, from_id, to_type, to_id,
      reference_type, description, created_by, payment_method, created_at
    ) values (
      v_half, 'safe', v_tx.from_id, 'external', null,
      'distribution',
      format('Вилучення частки, ½ від %s: дисплей iPhone 13 Pro Max. Перекваліфіковано з витрати «Обладнання» 01.08; узято наперед, сейф ЧП порожній',
             v_exp.amount),
      v_owners[i], v_tx.payment_method, v_tx.created_at + (i || ' seconds')::interval
    );
  end loop;

  raise notice 'Дисплей % грн: витрату знято, % і % отримали по % грн вилучення (аванс)',
    v_exp.amount, v_names[1], v_names[2], v_half;
end $$;
