-- Статус «Виконано» скасовано: він означав те саме, що «Готовий».
--
-- Через це кожен модуль читав його по-своєму — attention вважав виданим,
-- data-repairs закритим, дашборд брав з нього виторг, а робочий цикл тримав у
-- черзі на видачу. Живі рядки переводяться у handed_over: усі 13 мають
-- проставлений completed_at, тобто робота давно закінчена й пристрої віддані.
--
-- repair_status_log НЕ чіпаємо: це історія переходів, і переписати її означало б
-- стверджувати, що майстер натискав кнопку, якої не було. Інтерфейс рендерить
-- архівний ключ через окрему мапу.
update public.repairs
set status = 'handed_over'
where status = 'completed';

-- completed_at там, де його бракує: без нього ремонт випадає з розрахунку
-- прибутку по періодах, бо дашборд фільтрує саме за цією датою.
update public.repairs
set completed_at = coalesce(updated_at, created_at)
where status = 'handed_over' and completed_at is null;
