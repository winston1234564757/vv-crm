-- Купюр у мінусі не буває.
--
-- 01.08 сейф «Чистий прибуток» опинився з balance_cash = −3 498: зняли 12 000
-- там, де лежало 4 268. Загальна сума купюр при цьому лишалась правильною —
-- отже інший сейф числив на 3 498 більше готівки, ніж там фізично лежало.
-- Разом вірно, в розрізі по сейфах — брехня. Цей CHECK робить такий стан
-- неможливим на рівні бази, а не лише на рівні функції, яку можна обійти.
--
-- ПОРЯДОК КРИТИЧНИЙ, і в репозиторії вже є прецедент:
-- 20260729121000_safe_halves_check вмикав свій CHECK останнім, після того як усі
-- функції перевели на `safe_apply` — увімкнений раніше, він убив би кожну ще не
-- переведену й зупинив би прийом грошей посеред робочого дня, тихо.
-- Тут той самий порядок:
--   20260803120000 — бекфіл: мінус перекладено в аванс власника, сейф у нулі;
--   20260803130000 — легальний спосіб узяти наперед;
--   20260803140000 — і аж тепер заборона.
--
-- Другий крок з цього списку — не косметика, а умова, за якої заборона взагалі
-- має сенс. Запобіжник без легального обходу власника не спиняє: він однаково
-- візьме свої гроші, просто повз систему, і сейфи знову почнуть брехати.
--
-- Перевірено перед увімкненням: жодна функція в базі, крім `safe_apply`, не
-- пише в `safes`, і жоден сейф умови не порушує. `safe_apply` уже має власну
-- перевірку з людським повідомленням — цей CHECK її не замінює, а страхує на
-- випадок запису повз неї.
--
-- NOT VALID тут НЕ потрібен: рядків три, перевірка миттєва, а вибіркова
-- валідація лишила б діру, заради якої все й робилось.

alter table public.safes
  add constraint safes_halves_non_negative
  check (balance_cash >= 0 and balance_cashless >= 0);
