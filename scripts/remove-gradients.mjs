import fs from 'fs/promises';
import path from 'path';

async function walk(dir) {
  let results = [];
  const list = await fs.readdir(dir);
  for (let file of list) {
    file = path.resolve(dir, file);
    const stat = await fs.stat(file);
    if (stat && stat.isDirectory()) {
      results = results.concat(await walk(file));
    } else {
      if (file.endsWith('.tsx') || file.endsWith('.ts')) {
        results.push(file);
      }
    }
  }
  return results;
}

const patterns = [
  { match: /backdrop-blur-[a-z]+/g, replace: '' },
  { match: /bg-gradient-to-r from-\[#6366F1\] to-\[#06B6D4\]/g, replace: 'bg-violet' },
  { match: /bg-gradient-to-br from-cyan to-blue/g, replace: 'bg-cyan text-white' },
  { match: /bg-gradient-to-br from-violet to-iris/g, replace: 'bg-violet text-white' },
  { match: /bg-gradient-to-br from-amber to-orange-500/g, replace: 'bg-amber text-white' },
  { match: /bg-gradient-to-br from-emerald to-teal-600/g, replace: 'bg-emerald text-white' },
  { match: /bg-gradient-to-r from-violet\/20 via-violet\/5 to-violet\/20/g, replace: 'bg-violet/10' },
  { match: /bg-gradient-to-br from-violet\/5 to-iris\/5/g, replace: 'bg-violet-subtle' },
  { match: /bg-gradient-to-r from-violet\/10 to-iris\/10/g, replace: 'bg-violet-subtle' },
  { match: /bg-gradient-to-br from-cyan\/10 to-blue\/5/g, replace: 'bg-cyan/10' },
  { match: /bg-gradient-to-br from-amber\/10 to-orange-500\/5/g, replace: 'bg-amber/10' },
  { match: /bg-gradient-to-br from-emerald\/10 to-teal-600\/5/g, replace: 'bg-emerald/10' },
  { match: /bg-white\/[0-9]+/g, replace: 'bg-warm-surface' },
  { match: /dark:bg-zinc-900\/[0-9]+/g, replace: '' },
  { match: /shadow-lg shadow-[a-z]+\/5/g, replace: 'shadow-sm' }
];

async function run() {
  const files = await walk('./src');
  for (const file of files) {
    let content = await fs.readFile(file, 'utf8');
    let original = content;

    for (const { match, replace } of patterns) {
      content = content.replace(match, replace);
    }

    if (content !== original) {
      // Cleanup multiple spaces generated by replacing with empty string
      content = content.replace(/\s{2,}/g, (match) => {
        // Only replace if they are all spaces on the same line, don't mess up indentation
        if (!match.includes('\n')) return ' ';
        return match;
      });
      await fs.writeFile(file, content, 'utf8');
      console.log('Cleaned', file);
    }
  }
}

run().catch(console.error);
